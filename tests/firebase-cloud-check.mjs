// Explicit production smoke test. Not part of npm test or an emulator test glob.
// Creates only synthetic accounts and touches documents beneath their generated UIDs.
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { initializeApp, deleteApp } from "firebase/app";
import { initializeAuth, inMemoryPersistence, createUserWithEmailAndPassword, signInWithEmailAndPassword, signOut } from "firebase/auth";
import { getFirestore, doc, getDocFromServer, setDoc, deleteDoc, terminate, setLogLevel } from "firebase/firestore";
import { createFirestoreWorkspace, FirebaseHeadConflict } from "../lib/firebase-sync.ts";
import { blankWorkspace } from "../lib/model.ts";

if (!process.argv.includes("--production-opt-in")) {
  console.error("Refused: pass --production-opt-in to create isolated production test accounts.");
  process.exit(2);
}
assert.ok(!process.env.FIRESTORE_EMULATOR_HOST && !process.env.FIREBASE_AUTH_EMULATOR_HOST,
  "Production verification must not be routed to emulators");
const config = JSON.parse(await readFile(new URL("../portable/firebase-config.json", import.meta.url), "utf8"));
assert.ok(config.projectId && !config.projectId.startsWith("demo-"), "A real configured Firebase project is required");
assert.ok(config.apiKey && config.authDomain && config.appId, "Incomplete public Firebase configuration");
const runId = randomUUID();
const directory = new URL("../browser-results/", import.meta.url);
const browserPath = new URL("firebase-browser-account.json", directory);
const accountsPath = new URL(`firebase-cloud-accounts-${runId}.json`, directory);
const reportPath = new URL(`firebase-cloud-check-${runId}.json`, directory);
await mkdir(directory, { recursive: true });
try {
  await access(browserPath);
  throw Error("Browser account file already exists. Preserve it and coordinate with its current browser test before another run.");
} catch (problem) {
  if (problem?.code !== "ENOENT") throw problem;
}
setLogLevel("silent");
const clients = [];
const accounts = [];
const ownedUids = new Set();
const checks = [];
const report = { runId, projectId: config.projectId, startedAt: new Date().toISOString(), checks, passed: false };
let browserReady = false;
function record(name) {
  checks.push({ name, passed: true, at: new Date().toISOString() });
  console.log(`PASS ${name}`);
}
async function saveAccounts() {
  await writeFile(accountsPath, JSON.stringify({ projectId: config.projectId, runId, accounts }, null, 2) + "\n", { mode: 0o600 });
}
function client(label) {
  const app = initializeApp(config, `sayu-cloud-check-${runId}-${label}`);
  const auth = initializeAuth(app, { persistence: inMemoryPersistence });
  const db = getFirestore(app);
  const value = { app, auth, db };
  clients.push(value);
  return value;
}
function ownPath(db, uid, ...tail) {
  assert.ok(ownedUids.has(uid), "Only accounts generated by this run may be addressed");
  return doc(db, "users", uid, "workspaces", "main", ...tail);
}
function engine(connection, uid) {
  assert.ok(ownedUids.has(uid));
  assert.equal(connection.auth.currentUser?.uid, uid);
  return createFirestoreWorkspace(connection.db, uid, { isCurrent: () => connection.auth.currentUser?.uid === uid });
}
async function account(connection, purpose) {
  const email = `${purpose}-${randomUUID()}@example.invalid`;
  const password = `Sayu-${randomUUID()}-9!aA`;
  const result = await createUserWithEmailAndPassword(connection.auth, email, password);
  const credentials = { purpose, email, password, uid: result.user.uid, createdAt: new Date().toISOString() };
  ownedUids.add(credentials.uid);
  accounts.push(credentials);
  await saveAccounts();
  return credentials;
}
async function ownerReadAfterRulesPropagation(operation) {
  const expires = Date.now() + 65000;
  for (;;) {
    try { return await operation(); }
    catch (problem) {
      if (problem?.code !== "permission-denied" || Date.now() >= expires) throw problem;
      await new Promise(resolve => setTimeout(resolve, 5000));
    }
  }
}
async function denied(operation, name) {
  await assert.rejects(operation, problem => problem?.code === "permission-denied", name);
  record(name);
}
function nextHead(workspace, id) {
  let unsubscribe = () => {};
  let timer;
  const promise = new Promise((resolve, reject) => {
    timer = setTimeout(() => reject(Error("A second authenticated client did not receive the new head")), 25000);
    unsubscribe = workspace.watchHead(head => {
      if (head?.headId === id) resolve(head);
    }, reject);
  });
  return promise.finally(() => { clearTimeout(timer); unsubscribe(); });
}

try {
  // Keep this account empty so the browser can exercise migration from guest data.
  const browserClient = client("browser");
  const browserAccount = await account(browserClient, "sayu-browser");
  assert.equal(await ownerReadAfterRulesPropagation(() => engine(browserClient, browserAccount.uid).getHead()), null);
  await writeFile(browserPath, JSON.stringify({ ...browserAccount, projectId: config.projectId, emptyWorkspace: true }, null, 2) + "\n", { flag: "wx", mode: 0o600 });
  browserReady = true;
  record("reserved browser account authenticates and has no workspace");
  console.log("BROWSER_ACCOUNT_READY browser-results/firebase-browser-account.json");

  const firstClient = client("owner-first");
  const owner = await account(firstClient, "sayu-owner");
  await signOut(firstClient.auth);
  await signInWithEmailAndPassword(firstClient.auth, owner.email, owner.password);
  assert.equal(firstClient.auth.currentUser?.uid, owner.uid);
  record("email/password sign-in succeeds after sign-out");
  const secondClient = client("owner-second");
  await signInWithEmailAndPassword(secondClient.auth, owner.email, owner.password);
  assert.equal(secondClient.auth.currentUser?.uid, owner.uid);
  const first = engine(firstClient, owner.uid), second = engine(secondClient, owner.uid);
  assert.equal(await ownerReadAfterRulesPropagation(() => first.getHead()), null);
  const document = blankWorkspace();
  document.maps[0].name = `Synthetic sync ${runId.slice(0, 8)}`;
  const now = new Date().toISOString();
  document.nodes.push({
    id: randomUUID(), mapId: document.maps[0].id, title: "", kind: "메모",
    body: "한글🙂노드\n".repeat(10000), tags: [], source: "", confidence: "탐색 중",
    position: { x: 80, y: 120 }, createdAt: now, updatedAt: now,
  });
  const versionOne = await first.commit(document, null);
  const secondHead = await second.getHead();
  assert.equal(secondHead.headId, versionOne.id);
  assert.deepEqual((await second.readVersion(secondHead.headId)).document, document);
  record("two independent clients round-trip a Unicode chunked snapshot and empty title");

  const edited = structuredClone(document);
  edited.nodes[0].title = "Second client edit";
  edited.nodes[0].body += "\n두 번째 기기 저장 완료";
  const versionTwo = await second.commit(edited, versionOne.id);
  const observed = await nextHead(first, versionTwo.id);
  assert.equal(observed.sha256, versionTwo.sha256);
  assert.deepEqual((await first.readVersion(versionTwo.id)).document, edited);
  assert.deepEqual((await first.readVersion(versionOne.id)).document, document);
  record("head listener and second-client edits preserve the earlier immutable version");

  const staleEdit = structuredClone(document);
  staleEdit.nodes[0].title = "Stale client edit must not overwrite";
  await assert.rejects(() => first.commit(staleEdit, versionOne.id), problem =>
    problem instanceof FirebaseHeadConflict && problem.actual === versionTwo.id && problem.expected === versionOne.id);
  assert.equal((await second.getHead()).headId, versionTwo.id);
  record("compare-and-swap rejects a stale cloud write without changing head");

  const strangerClient = client("other-account");
  const stranger = await account(strangerClient, "sayu-other");
  assert.equal(await engine(strangerClient, stranger.uid).getHead(), null);
  await denied(() => getDocFromServer(ownPath(strangerClient.db, owner.uid)), "another account cannot read the owner head");
  await denied(() => getDocFromServer(ownPath(strangerClient.db, owner.uid, "versions", versionTwo.id)), "another account cannot read snapshot contents");
  await denied(() => setDoc(ownPath(strangerClient.db, owner.uid, "versions", randomUUID(), "chunks", "0000"), { index: 0, text: "foreign account synthetic probe" }),
    "another account cannot create data in the owner workspace");
  await denied(() => setDoc(ownPath(firstClient.db, owner.uid, "versions", versionTwo.id, "chunks", "0000"), { index: 0, text: "synthetic mutation probe" }),
    "an owner cannot mutate an existing immutable snapshot chunk");
  await denied(() => deleteDoc(ownPath(firstClient.db, owner.uid)), "an owner cannot delete the current head");
  assert.equal((await first.getHead()).headId, versionTwo.id);
  report.passed = true;
  report.syntheticOwnerUid = owner.uid;
  report.publishedVersionIds = [versionOne.id, versionTwo.id];
  report.credentialsFile = fileURLToPath(accountsPath);
  report.browserAccountFile = fileURLToPath(browserPath);
  console.log(`PASS production Firebase check (${checks.length} checks; credentials remain in ignored local files)`);
} catch (problem) {
  // Never print Firebase response objects, user credentials, or authentication tokens.
  report.failure = { name: problem?.name ?? "Error", code: problem?.code ?? null, message: String(problem?.message ?? "Unknown error") };
  console.error(`FAIL production Firebase check: ${problem?.code ?? problem?.name ?? "Error"}`);
  process.exitCode = 1;
} finally {
  report.finishedAt = new Date().toISOString();
  report.browserAccountReady = browserReady;
  await writeFile(reportPath, JSON.stringify(report, null, 2) + "\n", { mode: 0o600 });
  console.log(`REPORT browser-results/firebase-cloud-check-${runId}.json`);
  await Promise.allSettled(clients.map(async connection => {
    await terminate(connection.db);
    await deleteApp(connection.app);
  }));
}
